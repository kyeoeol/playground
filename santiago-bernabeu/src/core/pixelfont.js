/** Width of `text` in bits, including one bit of spacing between glyphs. */
export function textBits(text) {
  let bits = 0;
  for (const ch of text) bits += GLYPHS[ch][0].length + 1;
  return bits - 1;
}

/** Calls fn(bitX, bitY) for every lit bit of `text`, with y counted down from the top. */
export function forEachBit(text, fn) {
  let cx = 0;
  for (const ch of text) {
    const rows = GLYPHS[ch];
    rows.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) if (row[rx] === '1') fn(cx + rx, ry);
    });
    cx += rows[0].length + 1;
  }
}

/** Paint bitmap text with its top-left corner at x,y using bw×bh rectangles per bit. */
export function drawBitmapText(ctx, text, x, y, bw, bh, color) {
  ctx.fillStyle = color;
  forEachBit(text, (bx, by) => {
    ctx.fillRect(Math.round(x + bx * bw), Math.round(y + by * bh), Math.ceil(bw), Math.ceil(bh));
  });
}
